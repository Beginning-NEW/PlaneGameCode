#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

function fail(message) {
  throw new Error(message);
}

function dataLines(text) {
  return text.split(/\r?\n/).map((line) => line.trim()).filter((line) => line && !line.startsWith('#'));
}

function parseDirect(text) {
  return new Map(dataLines(text).map((line) => {
    const separator = line.indexOf(':');
    if (separator < 1) fail(`Invalid direct plugin line: ${line}`);
    return [line.slice(0, separator), line.slice(separator + 1)];
  }));
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

const args = Object.fromEntries(process.argv.slice(2).reduce((pairs, value, index, all) => {
  if (index % 2 === 0) pairs.push([value.replace(/^--/, ''), all[index + 1]]);
  return pairs;
}, []));
if (!args['input-time'] || !args['output-dir']) fail('--input-time and --output-dir are required');

const directory = new URL('.', import.meta.url);
const [directText, snapshotBytes, supplementBytes] = await Promise.all([
  readFile(new URL('direct-plugins.txt', directory), 'utf8'),
  readFile(new URL('update-center.snapshot.json', directory)),
  readFile(new URL('plugin-supplements.json', directory)),
]);
const direct = parseDirect(directText);
const snapshot = JSON.parse(snapshotBytes);
const supplements = JSON.parse(supplementBytes);
const metadata = new Map([
  ...Object.entries(snapshot.plugins),
  ...Object.entries(supplements.plugins),
]);

const closure = new Set();
const queue = [...direct.keys()];
while (queue.length) {
  const id = queue.shift();
  if (closure.has(id)) continue;
  const plugin = metadata.get(id);
  if (!plugin) fail(`Locked metadata is missing ${id}`);
  closure.add(id);
  for (const dependency of plugin.dependencies ?? []) {
    if (!dependency.optional) queue.push(dependency.name);
  }
}
for (const [id, version] of direct) {
  if (metadata.get(id)?.version !== version) fail(`Direct plugin ${id} is not pinned to ${version}`);
}

const ids = [...closure].sort();
const lockLines = [];
const installLines = [];
const hashLines = [];
for (const id of ids) {
  const plugin = metadata.get(id);
  if (!plugin.version || !plugin.sha256 || !plugin.url) fail(`Incomplete metadata for ${id}`);
  if (!plugin.url.startsWith('https://updates.jenkins.io/download/plugins/')) fail(`Non-official URL for ${id}`);
  const digest = Buffer.from(plugin.sha256, 'base64');
  if (digest.length !== 32) fail(`Invalid SHA-256 for ${id}`);
  lockLines.push(`${id}:${plugin.version}:${plugin.sha256}`);
  installLines.push(`${id}:${plugin.version}`);
  hashLines.push(`${digest.toString('hex')}  plugins/${id}.jpi`);
}

const lockText = `# Generated by generate-plugin-lock.mjs; ${ids.length} direct+transitive plugins.\n${lockLines.join('\n')}\n`;
const provenance = {
  schema: 2,
  generatedAt: args['input-time'],
  generator: 'ops/jenkins/controller-stage-b/generate-plugin-lock.mjs',
  core: snapshot.core,
  officialUpdateCenter: snapshot.source,
  historicalSupplements: {
    file: 'plugin-supplements.json',
    sha256: sha256(supplementBytes),
    source: supplements.source,
    verifiedAt: supplements.verifiedAt,
  },
  directCount: direct.size,
  pluginCount: ids.length,
  pluginsLockSha256: sha256(lockText),
};
const output = resolve(args['output-dir']);
await Promise.all([
  writeFile(join(output, 'plugins.lock'), lockText),
  writeFile(join(output, 'plugins.install.txt'), `${installLines.join('\n')}\n`),
  writeFile(join(output, 'plugins.sha256'), `${hashLines.join('\n')}\n`),
  writeFile(join(output, 'plugin-lock.provenance.json'), `${JSON.stringify(provenance, null, 2)}\n`),
]);
console.log(JSON.stringify(provenance));
